const dictionaries: Record<string, Record<string, string>> = { ru, en, uk };

const locales: Record<string, string> = { ru: "ru-RU", en: "en-US", uk: "uk-UA" };

let lang = $state("ru");

/** Switch the UI language; unknown codes fall back to Russian. */
export function setLanguage(value: string) {
  lang = dictionaries[value] ? value : "ru";
}

export function getLanguage(): string {
  return lang;
}

/** Translate `key` into the current language (fallback: Russian), interpolating `{name}` params. */
export function t(key: string, params?: Record<string, string | number>): string {
  let text = dictionaries[lang]?.[key] ?? ru[key as Key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** BCP-47 locale of the current language, for date/time formatting. */
export function locale(): string {
  return locales[lang] ?? "ru-RU";
}

/**
 * "{n} {form}" with plural rules of the current language.
 * The dictionary value holds 2 (one|many) or 3 (one|few|many, Slavic) forms separated by "|".
 */
export function plural(n: number, key: string): string {
  const forms = t(key).split("|");
  if (forms.length < 2) return `${n} ${forms[0] ?? ""}`.trim();
  if (forms.length === 2) return `${n} ${forms[n === 1 ? 0 : 1]}`;
  const m10 = n % 10;
  const m100 = n % 100;
  const i = m10 === 1 && m100 !== 11 ? 0 : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 1 : 2;
  return `${n} ${forms[i]}`;
}
